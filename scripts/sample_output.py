"""Run the README's sample requests (and the test IPs) against a deployment and save the results.

    uv run python scripts/sample_output.py https://<service-url> [--click-key KEY] [--out samples]

Writes samples/README.md (every request and response, with the served ad's text pulled out of the HTML),
samples/responses.json (raw responses) and one rendered .html per served ad, openable in a browser.
Uses only the public API (plus one /demo/serve call to show why the ranker picked an ad).
"""

